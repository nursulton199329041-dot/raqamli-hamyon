export type I18nKey = keyof typeof T;

export function translate(lang: Lang, key: I18nKey, args?: Record<string, string | number>): string {
  const row = T[key];
  const idx = LANGS.indexOf(lang);
  let v: string = row[idx < 0 ? 0 : idx] ?? row[0];
  if (args) for (const [k, val] of Object.entries(args)) v = v.split(`{${k}}`).join(String(val));
  return v;
}

